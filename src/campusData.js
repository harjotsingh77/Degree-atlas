export function getUniversityMedia(uni) {
  if (!uni) return null;
  const data = CAMPUS_MEDIA[uni.id];
  if (data) return data;

  return {
    hero: `/images/campus/${uni.id}.jpg`,
    thumbnails: [
      `/images/campus/${uni.id}.jpg`,
      '/images/campus/campus_exp2.webp',
      '/images/campus/infra_banner.webp'
    ],
    gallery: [
      { src: `/images/campus/${uni.id}.jpg`, title: uni.name }
    ]
  };
}
