export function getUniversityBadges(u) {
  if (!u) return [];
  // 1. Clean Type
  let type = u.type || '';
  type = type.replace(/Deemed-to-be-University/i, 'Deemed University')
             .replace(/Deemed-to-be University/i, 'Deemed University')
             .replace(/Institution of Eminence \/ Deemed/i, 'Deemed University')
             .replace(/Institution of Eminence \(Deemed\)/i, 'Deemed University')
             .replace(/UGC Autonomous Historic College/i, 'Autonomous College')
             .replace(/Autonomous Private College/i, 'Autonomous College')
             .replace(/Autonomous Constituent College/i, 'Autonomous College')
             .replace(/Central National University/i, 'Central University')
             .replace(/Central Collegiate University/i, 'Central University')
             .replace(/Central University \/ IoE/i, 'Central University')
             .replace(/Autonomous \/ Deemed Ecosystem/i, 'Autonomous Institution')
             .replace(/Private State University/i, 'State Private University');

  // 2. Clean NAAC (only valid NAAC grades: A++, A+, A, B++, B+, B)
  let naac = '';
  if (u.naacGrade) {
    const match = u.naacGrade.match(/NAAC\s*(A\+{1,2}|A|B\+{1,2}|B)/i);
    if (match) {
      naac = 'NAAC ' + match[1].toUpperCase();
    } else if (u.naacGrade.includes('A++')) {
      naac = 'NAAC A++';
    } else if (u.naacGrade.includes('A+')) {
      naac = 'NAAC A+';
    } else if (/A Grade/i.test(u.naacGrade)) {
      naac = 'NAAC A';
    }
  }

  // 3. Clean NIRF (only real NIRF ranks: NIRF #XX or NIRF Top XX)
  let nirf = '';
  if (u.nirfRank) {
    const rankMatch = u.nirfRank.match(/NIRF\s*(#\d+|Top\s*\d+)/i);
    if (rankMatch) {
      nirf = 'NIRF ' + rankMatch[1];
    } else {
      const hashMatch = u.nirfRank.match(/(#\d+)/);
      if (hashMatch) {
        nirf = 'NIRF ' + hashMatch[1];
      } else if (/Rank #(\d+)/i.test(u.nirfRank)) {
        nirf = 'NIRF #' + u.nirfRank.match(/Rank #(\d+)/i)[1];
      } else if (/Top\s*(\d+)/i.test(u.nirfRank)) {
        nirf = 'NIRF Top ' + u.nirfRank.match(/Top\s*(\d+)/i)[1];
      }
    }
  }

  return [type, naac, nirf].filter(Boolean);
}

/* ---------- Deterministic Ratings ---------- */
function _seed(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) - h + str.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

/** Returns { rating: number, ratingCount: number } for a programme id */
export function getProgrammeRating(id) {
  const s = _seed(id);
  const rating = +(3.8 + ((s % 110) / 100)).toFixed(1);   // 3.8 – 4.9
  const ratingCount = 120 + (s % 2381);                     // 120 – 2500
  return { rating: Math.min(rating, 4.9), ratingCount };
}

/** Returns { rating: number, ratingCount: number } for a university id */
export function getUniversityRating(id) {
  const s = _seed(id + '-uni');
  const rating = +(4.0 + ((s % 90) / 100)).toFixed(1);    // 4.0 – 4.9
  const ratingCount = 300 + (s % 4701);                     // 300 – 5000
  return { rating: Math.min(rating, 4.9), ratingCount };
}
